import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(
  root,
  "workers",
  "hot2000",
  "fixtures",
  "baseline-general.h2k",
);
const outputPath = path.join(
  root,
  "lib",
  "hot2000",
  "generated-recorder-fixture.ts",
);

const xml = readFileSync(sourcePath, "utf8");

if (typeof xml !== "string" || !xml.trim()) {
  throw new Error(`Recorder fixture is empty: ${sourcePath}`);
}

if (!xml.includes("<HouseFile") || !xml.includes("<?xml")) {
  throw new Error(`Recorder fixture does not look like H2K XML: ${sourcePath}`);
}

const output = `// Generated by scripts/generate-recorder-fixture.mjs — do not edit manually.
// Source: workers/hot2000/fixtures/baseline-general.h2k

export const RECORDER_FIXTURE_XML: string = ${JSON.stringify(xml)};
`;

writeFileSync(outputPath, output, "utf8");
console.log(
  `generate-recorder-fixture: wrote ${outputPath} (${xml.length} bytes from ${sourcePath})`,
);
